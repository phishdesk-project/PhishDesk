"""Composition report for the labelled corpus.

Every number in docs/data/composition.md comes from this module, run over
data/processed/records.jsonl and data/splits/splits-v0.json. The report holds
counts and file hashes only: no ids, senders, subjects or email text.
"""

from __future__ import annotations

import datetime as dt
import json
from collections import Counter
from collections.abc import Iterable
from pathlib import Path

from phishdesk_analysis.records import PHISHING_CATEGORIES, Category, EmailRecord, Tactic
from phishdesk_analysis.sources import sha256_of

SPLITS = ("train", "dev", "test")
MIN_REAL_PER_CATEGORY = 15


def load_splits(path: Path) -> dict[str, object]:
    data: dict[str, object] = json.loads(path.read_text(encoding="utf-8"))
    return data


def _table(header: list[str], rows: Iterable[list[object]]) -> list[str]:
    lines = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    lines += ["| " + " | ".join(str(c) for c in row) + " |" for row in rows]
    return lines


def _pct(part: int, whole: int) -> str:
    return f"{part / whole:.0%}" if whole else "-"


def composition_report(
    records: list[EmailRecord],
    splits: dict[str, object],
    hashed_files: dict[str, Path],
    generator_version: str,
    today: dt.date,
) -> tuple[str, list[str]]:
    """Return (markdown report, list of warnings)."""
    split_of: dict[str, str] = {}
    for name in SPLITS:
        ids = splits.get(name, [])
        assert isinstance(ids, list)
        split_of.update({str(i): name for i in ids})
    missing = [r.id for r in records if r.id not in split_of]
    if missing:
        raise ValueError(f"{len(missing)} records are not in any split, e.g. {missing[:3]}")

    cats = list(Category)
    total = len(records)
    real = [r for r in records if r.source != "synthetic"]
    by_cat_split = Counter((r.category, split_of[r.id]) for r in records)
    real_by_cat_split = Counter((r.category, split_of[r.id]) for r in real)
    by_cat_source = Counter((r.category, r.source) for r in records)
    sources = sorted({r.source for r in records}, key=lambda s: (s == "synthetic", s))
    dropped = splits.get("dropped_duplicates", {})
    dropped_count = len(dropped) if isinstance(dropped, dict) else 0

    lines = [
        "# Dataset composition (v0)",
        "",
        f"Generated by `python scripts/dataset_stats.py` on {today.isoformat()}. "
        "Do not edit by hand; rerun the script after any data change.",
        "",
        f"- Records: **{total}** ({len(real)} real, {total - len(real)} synthetic)",
        f"- Phishing: {sum(r.is_phishing for r in records)} · "
        f"Legitimate: {sum(not r.is_phishing for r in records)}",
        f"- Exact duplicates dropped before splitting: {dropped_count}",
        f"- Split seed: {splits.get('seed')} · ratios: {splits.get('ratios')} (group-aware)",
        f"- Synthetic generator version: {generator_version}",
        "",
        "## Category by split",
        "",
        "Real emails in brackets.",
        "",
    ]
    rows: list[list[object]] = []
    for c in cats:
        cells = [f"{by_cat_split[(c, s)]} ({real_by_cat_split[(c, s)]})" for s in SPLITS]
        rows.append([c.value, *cells, sum(by_cat_split[(c, s)] for s in SPLITS)])
    split_totals = [sum(1 for r in records if split_of[r.id] == s) for s in SPLITS]
    rows.append(["**total**", *split_totals, total])
    lines += _table(["category", *SPLITS, "total"], rows)

    lines += ["", "## Category by source", ""]
    rows = []
    for c in cats:
        cat_total = sum(by_cat_source[(c, s)] for s in sources)
        real_n = cat_total - by_cat_source[(c, "synthetic")]
        rows.append([c.value, *[by_cat_source[(c, s)] for s in sources], _pct(real_n, cat_total)])
    lines += _table(["category", *sources, "real share"], rows)

    lines += [
        "",
        "## Tactics",
        "",
        "Records carrying each tactic tag (a record can carry several).",
    ]
    lines.append("")
    rows = []
    for t in Tactic:
        phish = [r for r in records if r.is_phishing and t in r.tactics]
        legit = [r for r in records if not r.is_phishing and t in r.tactics]
        real_phish = sum(1 for r in phish if r.source != "synthetic")
        rows.append([t.value, len(phish), real_phish, len(legit)])
    lines += _table(["tactic", "phishing", "of which real", "legitimate"], rows)

    legit_total = sum(1 for r in records if not r.is_phishing)
    lu = sum(1 for r in records if r.category is Category.LEGIT_URGENT)
    lines += [
        "",
        f"Legitimate-but-urgent share of legitimate mail: {lu}/{legit_total} "
        f"({_pct(lu, legit_total)}).",
        "",
        "## Sources and licences",
        "",
    ]
    licence_rows: dict[str, list[object]] = {}
    for r in records:
        row = licence_rows.setdefault(r.source, [r.source, r.licence, r.redistributable, 0])
        row[3] = int(str(row[3])) + 1
    lines += _table(
        ["source", "licence", "redistributable", "records"], [licence_rows[s] for s in sources]
    )

    conf = Counter(r.label_confidence.value for r in real)
    lines += [
        "",
        "## Label quality (real emails)",
        "",
        f"- Confidence: high {conf['high']}, medium {conf['medium']}, low {conf['low']}",
        f"- Labellers: {', '.join(sorted({r.label_by for r in real})) or '-'}",
        "",
        "## Input file hashes (SHA-256)",
        "",
    ]
    lines += _table(
        ["file", "sha256"],
        [[name, f"`{sha256_of(p)}`"] for name, p in sorted(hashed_files.items())],
    )

    warnings: list[str] = []
    for c in cats:
        real_n = sum(real_by_cat_split[(c, s)] for s in SPLITS)
        if real_n < MIN_REAL_PER_CATEGORY:
            warnings.append(
                f"{c.value}: only {real_n} real emails; its scores will rely mainly on "
                "synthetic data"
            )
        for s in ("dev", "test"):
            if by_cat_split[(c, s)] == 0:
                warnings.append(f"{c.value}: no records in {s}")
            elif real_by_cat_split[(c, s)] == 0:
                warnings.append(f"{c.value}: {s} contains no real emails")
    for t in (Tactic.URGENCY, Tactic.IMPERSONATION):
        if not any(t in r.tactics and r.source != "synthetic" for r in records):
            warnings.append(f"tactic {t.value}: not present on any real email")
    phishing_cats = [c for c in cats if c in PHISHING_CATEGORIES]
    if not all(by_cat_split[(c, "test")] for c in phishing_cats):
        warnings.append("not every phishing category is represented in test")

    lines += ["", "## Warnings and known limitations", ""]
    lines += [f"- {w}" for w in warnings] or ["- None"]
    return "\n".join(lines) + "\n", warnings
